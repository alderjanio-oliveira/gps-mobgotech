package org.traccar.health;

import com.fasterxml.jackson.databind.ObjectMapper;
import liquibase.Contexts;
import liquibase.Liquibase;
import liquibase.database.jvm.JdbcConnection;
import liquibase.resource.DirectoryResourceAccessor;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.traccar.model.Device;
import org.traccar.model.Position;
import org.traccar.notification.NotificationOutbox;
import org.traccar.storage.StorageException;

import java.nio.file.Path;
import java.util.Date;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

public class DeviceHealthServiceTest {

    private DeviceHealthService health;
    private Device device;
    private Position position;
    private JdbcDataSource source;

    @BeforeEach
    public void setup() throws Exception {
        source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE tc_devices (id INT PRIMARY KEY)");
            statement.execute("INSERT INTO tc_devices VALUES (1)");
            statement.execute("CREATE TABLE tc_events (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "type VARCHAR(128),servertime TIMESTAMP,eventtime TIMESTAMP,deviceid INT,positionid BIGINT,"
                    + "geofenceid INT,maintenanceid INT,distancereminderid INT,attributes VARCHAR(4000))");
            try (var resources = new DirectoryResourceAccessor(Path.of("schema"))) {
                new Liquibase("changelog-mobgo-notification-outbox.xml", resources, new JdbcConnection(connection))
                        .update(new Contexts());
                new Liquibase("changelog-mobgo-health.xml", resources, new JdbcConnection(connection))
                        .update(new Contexts());
            }
        }
        health = new DeviceHealthService(new NotificationOutbox(source, new ObjectMapper()), source);
        device = new Device();
        device.setId(1);
        device.setLastUpdate(new Date(0));
        device.set("monitoring.enabled", true);
        position = new Position();
        position.setDeviceId(1);
        position.setFixTime(new Date(0));
        position.setValid(true);
    }

    private long events() throws Exception {
        try (var connection = source.getConnection(); var statement = connection.createStatement();
                var rows = statement.executeQuery("SELECT COUNT(*) FROM tc_events")) {
            rows.next();
            return rows.getLong(1);
        }
    }

    private void fresh(long now, boolean gps) throws Exception {
        device.setLastUpdate(new Date(now));
        if (gps) {
            position.setValid(true);
            position.setFixTime(new Date(now));
        }
        health.evaluate(device, position, new Date(now));
    }

    @Test
    public void prolongedSilenceOpensOnceAndRecoveryRequiresStability() throws Exception {
        health.evaluate(device, position, new Date(900000));
        health.evaluate(device, position, new Date(900001));
        assertEquals(1, events());
        fresh(900002, true);
        fresh(930002, true);
        assertEquals(1, events());
        fresh(960002, true);
        assertEquals(2, events());
        assertTrue(health.activeKinds(1).isEmpty());
        assertEquals(1, health.incidents(1).size());
        assertEquals("recovered", health.incidents(1).getFirst().recoveryReason());
    }

    @Test
    public void invalidGpsWaitsForToleranceAndDoesNotFollowConnectionStatus() throws Exception {
        device.set("monitoring.gpsMinutes", 1);
        fresh(0, true);
        position.setValid(false);
        fresh(1000, false);
        fresh(31000, false);
        assertEquals(0, events());
        fresh(61000, false);
        assertEquals(1, events());
        assertEquals("gps", health.activeKinds(1).getFirst());
        fresh(62000, true);
        fresh(122000, true);
        assertEquals(2, events());
    }

    @Test
    public void unknownOrFutureCommunicationNeverConfirmsAnIncident() throws Exception {
        device.setLastUpdate(null);
        health.evaluate(device, position, new Date(900000));
        device.setLastUpdate(new Date(1000000));
        health.evaluate(device, position, new Date(900000));
        assertEquals(0, events());
    }

    @Test
    public void disablingMonitoringClosesHistoryWithoutRecoveryNotification() throws Exception {
        health.evaluate(device, position, new Date(900000));
        device.set("monitoring.enabled", false);
        health.evaluate(device, position, new Date(900001));
        assertEquals(1, events());
        assertTrue(health.activeDeviceIds().isEmpty());
        assertEquals("monitoringDisabled", health.incidents(1).getFirst().recoveryReason());
    }

    @Test
    public void domainTransitionRollsBackIfOutboxInsertFails() throws Exception {
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("ALTER TABLE tc_event_outbox ADD CONSTRAINT reject_insert CHECK (eventid < 0)");
        }
        assertThrows(StorageException.class, () -> health.evaluate(device, position, new Date(900000)));
        assertTrue(health.activeDeviceIds().isEmpty());
        assertTrue(health.incidents(1).isEmpty());
        assertEquals(0, events());
    }

    @Test
    public void recoveryAlertCanBeDisabledWithoutLeavingIncidentOpen() throws Exception {
        device.set("monitoring.recovery", false);
        health.evaluate(device, position, new Date(900000));
        fresh(900001, true);
        fresh(960001, true);
        assertEquals(1, events());
        assertFalse(health.incidents(1).isEmpty());
        assertTrue(health.activeDeviceIds().isEmpty());
    }
}

package org.traccar.notification;

import com.fasterxml.jackson.databind.ObjectMapper;
import liquibase.Contexts;
import liquibase.Liquibase;
import liquibase.database.jvm.JdbcConnection;
import liquibase.resource.DirectoryResourceAccessor;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.traccar.model.Event;
import org.traccar.model.Position;
import org.traccar.storage.StorageException;

import java.nio.file.Path;
import java.util.Date;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

public class NotificationOutboxTest {

    private JdbcDataSource source;
    private NotificationOutbox outbox;
    private Position position;

    @BeforeEach
    public void setup() throws Exception {
        source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE tc_events (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "type VARCHAR(128),servertime TIMESTAMP,eventtime TIMESTAMP,deviceid INT,positionid BIGINT,"
                    + "geofenceid INT,maintenanceid INT,distancereminderid INT,attributes VARCHAR(4000))");
            statement.execute("CREATE TABLE tc_distance_reminders (id INT PRIMARY KEY, startvalue DOUBLE, "
                    + "thresholddistance DOUBLE,status VARCHAR(16),notifiedat TIMESTAMP)");
            statement.execute("INSERT INTO tc_distance_reminders VALUES (1,0,1000,'pending',NULL)");
            try (var resources = new DirectoryResourceAccessor(Path.of("schema"))) {
                new Liquibase("changelog-mobgo-notification-outbox.xml", resources, new JdbcConnection(connection))
                        .update(new Contexts());
            }
        }
        outbox = new NotificationOutbox(source, new ObjectMapper());
        position = new Position();
        position.setDeviceId(1);
        position.setDeviceTime(new Date());
        position.setFixTime(new Date());
        position.setServerTime(new Date());
        position.set(Position.KEY_TOTAL_DISTANCE, 1000.0);
    }

    private Event event() {
        Event event = new Event(Event.TYPE_DISTANCE_REMINDER, position);
        event.setDistanceReminderId(1);
        return event;
    }

    private String scalar(String sql) throws Exception {
        try (var connection = source.getConnection(); var statement = connection.createStatement();
                var rows = statement.executeQuery(sql)) {
            assertTrue(rows.next());
            return rows.getString(1);
        }
    }

    private void sql(String sql) throws Exception {
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private NotificationOutbox.Delivery queued(String channel) throws Exception {
        Event event = event();
        assertTrue(outbox.save(event, position));
        String token = outbox.claimEvent(event.getId());
        outbox.expand(event, token, List.of(new NotificationOutbox.Recipient(1, 1, channel)), "expanded");
        return outbox.dueDeliveries().getFirst();
    }

    @Test
    public void reminderEventAndOutboxCommitTogetherAndSurviveRestart() throws Exception {
        Event event = event();
        assertTrue(outbox.save(event, position));
        assertEquals("notified", scalar("SELECT status FROM tc_distance_reminders WHERE id=1"));
        assertEquals("1", scalar("SELECT COUNT(*) FROM tc_events"));
        var restarted = new NotificationOutbox(source, new ObjectMapper());
        assertEquals(List.of(event.getId()), restarted.pendingEvents());
        assertEquals(1000, restarted.position(event.getId()).getDouble(Position.KEY_TOTAL_DISTANCE));
        assertFalse(restarted.save(event(), position));
        assertEquals("1", scalar("SELECT COUNT(*) FROM tc_events"));
    }

    @Test
    public void failureAfterEventInsertRollsBackReachingAndEvent() throws Exception {
        sql("ALTER TABLE tc_event_outbox ADD CONSTRAINT reject_insert CHECK (eventid < 0)");
        Event event = event();
        assertThrows(StorageException.class, () -> outbox.save(event, position));
        assertEquals(0, event.getId());
        assertEquals("pending", scalar("SELECT status FROM tc_distance_reminders WHERE id=1"));
        assertEquals("0", scalar("SELECT COUNT(*) FROM tc_events"));
    }

    @Test
    public void concurrentReachingPersistsOnlyOneEvent() throws Exception {
        var start = new CountDownLatch(1);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var first = executor.submit(() -> {
                start.await();
                return outbox.save(event(), position);
            });
            var second = executor.submit(() -> {
                start.await();
                return outbox.save(event(), position);
            });
            start.countDown();
            int saved = (first.get(10, TimeUnit.SECONDS) ? 1 : 0) + (second.get(10, TimeUnit.SECONDS) ? 1 : 0);
            assertEquals(1, saved);
        }
        assertEquals("1", scalar("SELECT COUNT(*) FROM tc_events"));
    }

    @Test
    public void eventLeaseAndFanOutAreIdempotent() throws Exception {
        Event event = event();
        outbox.save(event, position);
        String token = outbox.claimEvent(event.getId());
        assertNotNull(token);
        assertNull(outbox.claimEvent(event.getId()));
        var recipients = List.of(new NotificationOutbox.Recipient(1, 1, "mail"));
        outbox.expand(event, token, recipients, "expanded");
        outbox.expand(event, token, recipients, "expanded");
        assertEquals("1", scalar("SELECT COUNT(*) FROM tc_notification_deliveries"));
    }

    @Test
    public void failedAdapterRetriesPersistentlyAndStopsAtLimit() throws Exception {
        var candidate = queued("mail");
        for (int attempt = 1; attempt <= NotificationOutbox.MAX_ATTEMPTS; attempt++) {
            var claimed = outbox.claim(candidate);
            assertNotNull(claimed);
            assertEquals(attempt, claimed.attempts());
            assertNull(outbox.claim(candidate));
            outbox.finish(claimed, "failed", "SmtpUnavailable");
            sql("UPDATE tc_notification_deliveries SET nextattempt=TIMESTAMP '2000-01-01 00:00:00'");
            var pending = new NotificationOutbox(source, new ObjectMapper()).dueDeliveries();
            if (attempt < NotificationOutbox.MAX_ATTEMPTS) {
                assertEquals(1, pending.size());
                candidate = pending.getFirst();
            } else {
                assertTrue(pending.isEmpty());
            }
        }
        assertEquals("failed", scalar("SELECT state FROM tc_notification_deliveries"));
        assertEquals("5", scalar("SELECT COUNT(*) FROM tc_notification_attempts"));
    }

    @Test
    public void uncertainPhysicalCommandIsNeverAutomaticallyRepeated() throws Exception {
        var claimed = outbox.claim(queued("command"));
        sql("UPDATE tc_notification_deliveries SET leaseuntil=TIMESTAMP '2000-01-01 00:00:00'");
        assertTrue(outbox.dueDeliveries().isEmpty());
        assertEquals("uncertain", scalar("SELECT state FROM tc_notification_deliveries"));
        outbox.finish(claimed, "accepted", null);
        assertEquals("uncertain", scalar("SELECT state FROM tc_notification_deliveries"));
    }

    @Test
    public void expiredWorkerCannotOverwriteNewAttempt() throws Exception {
        var first = outbox.claim(queued("mail"));
        sql("UPDATE tc_notification_deliveries SET leaseuntil=TIMESTAMP '2000-01-01 00:00:00'");
        var second = outbox.claim(outbox.dueDeliveries().getFirst());
        outbox.finish(first, "accepted", null);
        assertEquals("sending", scalar("SELECT state FROM tc_notification_deliveries"));
        outbox.finish(second, "accepted", null);
        assertEquals("accepted", scalar("SELECT state FROM tc_notification_deliveries"));
        assertEquals(2, outbox.attempts(second.id(), 1, 1).size());
        assertTrue(outbox.attempts(second.id(), 1, 2).isEmpty());
    }

    @Test
    public void deliveryHistoryIsScopedToRecipient() throws Exception {
        outbox.claim(queued("mail"));
        assertEquals(1, outbox.deliveries(1, 1).size());
        assertTrue(outbox.deliveries(1, 2).isEmpty());
        assertTrue(outbox.deliveries(2, 1).isEmpty());
    }
}
